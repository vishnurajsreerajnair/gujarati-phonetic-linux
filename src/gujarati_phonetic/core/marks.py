# A letter followed by its marks at the end of the text, as reMarks_ in
# composetextinput.js: a base letter with non-spacing marks (and letters
# between them), or base letters with non-spacing marks ending in a spacing
# mark.
_BASE = f"[^{NON_SPACING_MARKS}{OTHER_MARKS}]"
_NON_SPACING = f"[{NON_SPACING_MARKS}]"
_SPACING = f"[{OTHER_MARKS}]"
_TRAILING_CLUSTER = re.compile(
    f"((?:{_BASE}(?:{_NON_SPACING}{_BASE}?)+)"
    f"|(?:(?:{_BASE}{_NON_SPACING}*)+{_SPACING}))$"
)


def trailing_cluster_length(text: str) -> int | None:
    """Return the length of the letter cluster with marks ending the text.

    Args:
        text: The text up to the point where a commit would split it.

    Returns:
        The number of characters of the trailing cluster, None if the text
        does not end with a letter and its marks.
    """
    found = _TRAILING_CLUSTER.search(text)
    return len(found.group(0)) if found else None
